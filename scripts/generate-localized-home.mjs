function renderLocaleStructuredData(locale, canonical) {
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Organization",
        "@id": `${SITE_URL}/#organization`,
        name: "NFG",
        url: `${SITE_URL}/`,
        logo: `${SITE_URL}/assets/brand/nfg-favicon-512.png`,
      },
      {
        "@type": "WebSite",
        "@id": `${SITE_URL}/#website`,
        name: "NFG",
        url: `${SITE_URL}/`,
        publisher: { "@id": `${SITE_URL}/#organization` },
      },
      {
        "@type": "CollectionPage",
        name: locale.title,
        description: locale.description,
        url: canonical,
        inLanguage: locale.lang,
        isPartOf: { "@id": `${SITE_URL}/#website` },
        mainEntity: {
          "@type": "ItemList",
          itemListElement: locale.projects.map((project, index) => ({
            "@type": "ListItem",
            position: index + 1,
            name: project.title,
            url: PROJECTS[index].href,
          })),
        },
      },
    ],
  };
}

function renderSitemap() {
  const urls = locales.map((locale) => localeUrl(locale));
  const entries = urls
    .map(
      (url) => `  <url>
    <loc>${escapeHtml(url)}</loc>
    <lastmod>${data.lastModified}</lastmod>
  </url>`,
    )
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</urlset>
`;
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n/g, "\n");
}

function renderLlmsText() {
  const localeLinks = locales
    .map((locale) => `- [${locale.autonym}](${localeUrl(locale)})`)
    .join("\n");
  const productLinks = PROJECTS.map(
    (project) => `- [${project.name}](${project.href})`,
  ).join("\n");

  return `# NFG

> NFG publishes tools and ready-to-install packages for Anvil Empires players.

## Localized project index

${localeLinks}

## Products

${productLinks}

## Notes

- The Russian and Spanish localization links point to ready release archives.
- NFG Hub is the Windows catalog and installer for supported NFG packages.
- Canonical page metadata and sitemap.xml remain the authoritative discovery sources.
`;
}

function localeUrl(locale) {
  return `${SITE_URL}/${locale.slug}/`;
}

function externalLinkIcon() {
  return `<svg aria-hidden="true" viewBox="0 0 20 20">
              <path d="M5 15 15 5M7 5h8v8" />
            </svg>`;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function escapeAttr(value) {
  return escapeHtml(value).replaceAll('"', "&quot;");
}

function jsonForHtml(value) {
  return JSON.stringify(value).replaceAll("<", "\\u003c");
}

function count(value, needle) {
  return value.split(needle).length - 1;
}
