import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
const contentPath = path.join(rootDir, "content", "home.locales.json");
const data = JSON.parse(await readFile(contentPath, "utf8"));
const checkOnly = process.argv.includes("--check");

const SITE_URL = "https://nfg-system.online";
const OG_IMAGE = `${SITE_URL}/assets/brand/nfg-og-image.png`;
const DISCORD_URL = "https://discord.gg/RNJaFUyeyx";
const GENERATED_NOTICE =
  "<!-- Generated by scripts/generate-localized-home.mjs. Edit content/home.locales.json. -->";

const PROJECTS = [
  {
    key: "planner",
    name: "Anvil Planner",
    href: "https://anvil-planner.nfg-system.online/",
  },
  {
    key: "russian",
    name: "Anvil Empires Russian localization",
    href: "https://github.com/nullith2/anvil-empires-russian/releases/download/v1.0.1/Anvil-Empires-Russian-v1.0.1-steam-build-24619810.zip",
  },
  {
    key: "spanish",
    name: "Anvil Empires Spanish localization",
    href: "https://github.com/Aneonfas/anvil-empires-localizations/releases/download/es-v0.1.0/Anvil-Empires-Spanish-v0.1.0-steam-build-24619810.zip",
  },
  {
    key: "forge",
    name: "Anvil Forge Helper",
    href: "https://github.com/nullith2/Anvil-forge-helper",
  },
  {
    key: "hub",
    name: "NFG Hub",
    href: "https://github.com/Aneonfas/nfg-hub/releases/download/v0.3.0/NFG-Hub-v0.3.0-win-x64.zip",
  },
];

const locales = Object.entries(data.locales).map(([slug, locale]) => ({
  slug,
  ...locale,
}));
const defaultLocale = locales.find((locale) => locale.slug === "en");

validateSource();

const outputs = new Map();
outputs.set("index.html", renderRootFallback());
for (const locale of locales) {
  outputs.set(`${locale.slug}/index.html`, renderLocalePage(locale));
}
outputs.set("sitemap.xml", renderSitemap());
outputs.set("llms.txt", renderLlmsText());
validateOutputs();

if (checkOnly) {
  const drift = [];
  for (const [relativePath, expected] of outputs) {
    const absolutePath = path.join(rootDir, relativePath);
    let actual;
    try {
      actual = await readFile(absolutePath, "utf8");
    } catch {
      drift.push(`${relativePath} is missing`);
      continue;
    }

    if (normalizeLineEndings(actual) !== normalizeLineEndings(expected)) {
      drift.push(`${relativePath} is out of date`);
    }
  }

  if (drift.length > 0) {
    throw new Error(`Localized homepage drift:\n- ${drift.join("\n- ")}`);
  }

  console.log(`Localized homepage is current (${outputs.size} generated files).`);
} else {
  for (const [relativePath, content] of outputs) {
    const absolutePath = path.join(rootDir, relativePath);
    await mkdir(path.dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, content, "utf8");
  }

  console.log(`Generated ${outputs.size} localized homepage files.`);
}

function validateSource() {
  if (!data.lastModified || !/^\d{4}-\d{2}-\d{2}$/.test(data.lastModified)) {
    throw new Error("lastModified must use YYYY-MM-DD.");
  }
  if (!data.assetRevision || !/^[a-zA-Z0-9._-]+$/.test(data.assetRevision)) {
    throw new Error("assetRevision must be a cache-safe token.");
  }

  if (locales.length !== 10) {
    throw new Error(`Expected 10 locales, found ${locales.length}.`);
  }
  if (!defaultLocale) throw new Error("The default English locale is missing.");

  const slugs = new Set();
  const hreflangs = new Set();
  for (const locale of locales) {
    if (!/^[a-z]{2}(?:-[a-z]{2})?$/.test(locale.slug)) {
      throw new Error(`Invalid locale slug: ${locale.slug}`);
    }
    if (slugs.has(locale.slug)) throw new Error(`Duplicate slug: ${locale.slug}`);
    if (hreflangs.has(locale.hreflang.toLowerCase())) {
      throw new Error(`Duplicate hreflang: ${locale.hreflang}`);
    }
    if (!Array.isArray(locale.projects) || locale.projects.length !== PROJECTS.length) {
      throw new Error(`${locale.slug} must contain ${PROJECTS.length} projects.`);
    }
    slugs.add(locale.slug);
    hreflangs.add(locale.hreflang.toLowerCase());
  }
}

function validateOutputs() {
  const expectedAlternateCount = locales.length + 1;

  for (const locale of locales) {
    const relativePath = `${locale.slug}/index.html`;
    const html = outputs.get(relativePath);
    const canonical = localeUrl(locale);
    if (!html.includes(`<link rel="canonical" href="${canonical}" />`)) {
      throw new Error(`${relativePath} is missing its self-canonical URL.`);
    }
    if (count(html, '<link rel="alternate" hreflang=') !== expectedAlternateCount) {
      throw new Error(`${relativePath} has an incomplete hreflang cluster.`);
    }
    if (count(html, 'class="project-row project-row-active"') !== PROJECTS.length) {
      throw new Error(`${relativePath} has an unexpected project count.`);
    }
    if (count(html, 'aria-current="page"') !== 1) {
      throw new Error(`${relativePath} must mark exactly one current language.`);
    }

    const jsonLd = html.match(
      /<script type="application\/ld\+json">([\s\S]*?)<\/script>/,
    );
    if (!jsonLd) throw new Error(`${relativePath} is missing JSON-LD.`);
    JSON.parse(jsonLd[1]);
  }

  const sitemap = outputs.get("sitemap.xml");
  const canonicalUrls = locales.map(localeUrl);
  if (count(sitemap, "<url>") !== canonicalUrls.length) {
    throw new Error("The sitemap canonical URL count is incorrect.");
  }
  for (const url of canonicalUrls) {
    if (!sitemap.includes(`<loc>${url}</loc>`)) {
      throw new Error(`The sitemap is missing ${url}.`);
    }
  }

  const rootFallback = outputs.get("index.html");
  const englishUrl = localeUrl(defaultLocale);
  if (!rootFallback.includes('<meta name="robots" content="noindex,follow" />')) {
    throw new Error("The root fallback must not be indexed.");
  }
  if (!rootFallback.includes(`<link rel="canonical" href="${englishUrl}" />`)) {
    throw new Error("The root fallback must point to the canonical English page.");
  }
  if (!rootFallback.includes('content="0; url=/en/"')) {
    throw new Error("The root fallback must continue to /en/ without a language chooser.");
  }
}

function renderLocalePage(locale) {
  const canonical = localeUrl(locale);
  const assetPrefix = "../";
  const projectCards = locale.projects
    .map((project, index) => renderProjectCard(project, PROJECTS[index], index))
    .join("\n\n");
  const structuredData = renderLocaleStructuredData(locale, canonical);
  const ogAlternates = locales
    .filter((candidate) => candidate.slug !== locale.slug)
    .map(
      (candidate) =>
        `    <meta property="og:locale:alternate" content="${escapeAttr(candidate.ogLocale)}" />`,
    )
    .join("\n");

  return `<!doctype html>
<html lang="${escapeAttr(locale.lang)}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeHtml(locale.title)}</title>
    <meta name="description" content="${escapeAttr(locale.description)}" />
    <meta name="robots" content="index,follow,max-image-preview:large" />
    <link rel="canonical" href="${canonical}" />
${renderAlternateLinks("    ")}
${renderFavicons(assetPrefix)}
    <meta name="theme-color" content="#ffffff" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="NFG" />
    <meta property="og:url" content="${canonical}" />
    <meta property="og:title" content="${escapeAttr(locale.title)}" />
    <meta property="og:description" content="${escapeAttr(locale.description)}" />
    <meta property="og:locale" content="${escapeAttr(locale.ogLocale)}" />
${ogAlternates}
    <meta property="og:image" content="${OG_IMAGE}" />
    <meta property="og:image:alt" content="NFG" />
    <meta name="twitter:card" content="summary_large_image" />
    <script type="application/ld+json">${jsonForHtml(structuredData)}</script>
    <link rel="stylesheet" href="${assetPrefix}assets/home.css?v=${escapeAttr(data.assetRevision)}" />
  </head>
  <body>
    ${GENERATED_NOTICE}
${renderLocaleChoiceScript()}
    <a class="skip-link" href="#projects">${escapeHtml(locale.skipLink)}</a>

    <header class="site-header">
      <div class="shell header-inner">
        <a class="wordmark" href="/" aria-label="${escapeAttr(locale.homeAria)}">NFG</a>
        <div class="header-actions">
          <a class="section-link" href="#projects">${escapeHtml(locale.projectsNav)}</a>
${renderLanguageMenu(locale)}
        </div>
      </div>
    </header>

    <main class="shell page-main">
      <h1 class="visually-hidden">${escapeHtml(locale.title)}</h1>
      <section class="project-list" id="projects" aria-label="${escapeAttr(locale.projectsAria)}">
${projectCards}
      </section>
    </main>

${renderFooter(locale.discordAria, "    ")}
  </body>
</html>
`;
}

function renderRootFallback() {
  const englishUrl = localeUrl(defaultLocale);
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>NFG</title>
    <meta name="robots" content="noindex,follow" />
    <meta http-equiv="refresh" content="0; url=/en/" />
    <link rel="canonical" href="${englishUrl}" />
  </head>
  <body>
    ${GENERATED_NOTICE}
    <p><a href="/en/">Continue to NFG</a></p>
  </body>
</html>
`;
}

function renderProjectCard(project, definition, index) {
  const position = String(index + 1).padStart(2, "0");
  return `        <article class="project-row project-row-active">
          <div class="project-index" aria-hidden="true">${position}</div>
          <h2 class="project-title">${escapeHtml(project.title)}</h2>
          <div class="project-copy">
            <p>${escapeHtml(project.primary)}</p>
            <p class="project-copy-secondary">${escapeHtml(project.secondary)}</p>
          </div>
          <a
            class="project-link"
            href="${escapeAttr(definition.href)}"
            target="_blank"
            rel="noreferrer"
            aria-label="${escapeAttr(project.aria)}"
          >
            <span>${escapeHtml(project.action)}</span>
            ${externalLinkIcon()}
          </a>
        </article>`;
}

function renderLanguageMenu(currentLocale) {
  const links = locales
    .map((locale) => {
      const current = locale.slug === currentLocale.slug ? ' aria-current="page"' : "";
      const href = `/${locale.slug}/`;
      return `              <a href="${escapeAttr(href)}" data-locale-choice="${escapeAttr(locale.slug)}" lang="${escapeAttr(locale.lang)}" hreflang="${escapeAttr(locale.hreflang)}"${current}>${escapeHtml(locale.autonym)}</a>`;
    })
    .join("\n");

  return `          <details class="language-menu">
            <summary aria-label="${escapeAttr(currentLocale.languageLabel)}">${escapeHtml(currentLocale.shortLabel)}</summary>
            <nav class="language-options" aria-label="${escapeAttr(currentLocale.languageLabel)}">
${links}
            </nav>
          </details>`;
}

function renderLocaleChoiceScript() {
  return `    <script>
      document.addEventListener("click", (event) => {
        const link = event.target.closest("[data-locale-choice]");
        const locale = link?.dataset.localeChoice;
        if (!locale) return;
        document.cookie = "nfg_locale=" + encodeURIComponent(locale) + "; Path=/; Max-Age=31536000; SameSite=Lax; Secure";
      });
    </script>`;
}

function renderAlternateLinks(indent) {
  const links = locales
    .map(
      (locale) =>
        `${indent}<link rel="alternate" hreflang="${escapeAttr(locale.hreflang)}" href="${localeUrl(locale)}" />`,
    )
    .join("\n");
  return `${links}\n${indent}<link rel="alternate" hreflang="x-default" href="${localeUrl(defaultLocale)}" />`;
}

function renderFavicons(prefix) {
  return `    <link rel="icon" href="${prefix}favicon.ico" sizes="any" />
    <link rel="icon" href="${prefix}assets/brand/nfg-favicon-48.png" sizes="48x48" type="image/png" />
    <link rel="icon" href="${prefix}assets/brand/nfg-favicon-192.png" sizes="192x192" type="image/png" />
    <link rel="apple-touch-icon" href="${prefix}assets/brand/nfg-apple-touch-icon.png" sizes="180x180" />`;
}

